// Package gofuzz implements the Go-native fuzzing engine. It generates a
// testing.F fuzz target into the head snapshot, fuzzes the target for a bounded
// amount of time and reports reproducible head-side panics or crashes. It does
// not prove differential equivalence; that is the go-differential engine's job.
package gofuzz

import (
	"bytes"
	"encoding/base64"
	"encoding/binary"
	"encoding/json"
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

var identifierPattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// encodeSeed converts one JSON argument array into the length-prefixed wire
// format decoded by the generated fuzz target.
func encodeSeed(args []json.RawMessage) ([]byte, error) {
	var buffer bytes.Buffer
	for _, arg := range args {
		if len(arg) > 1<<20 {
			return nil, fmt.Errorf("seed argument exceeds 1 MiB")
		}
		var prefix [4]byte
		binary.BigEndian.PutUint32(prefix[:], uint32(len(arg)))
		buffer.Write(prefix[:])
		buffer.Write(arg)
	}
	return buffer.Bytes(), nil
}

// GenerateTarget renders the fuzz target source for the target function.
func GenerateTarget(importPath, functionName, contractKind string, seeds [][]byte) ([]byte, error) {
	if strings.TrimSpace(importPath) == "" {
		return nil, fmt.Errorf("target package import path is required")
	}
	for _, r := range importPath {
		if r <= ' ' || r == '"' || r == '`' || r == '\\' {
			return nil, fmt.Errorf("target package import path %q contains unsupported characters", importPath)
		}
	}
	if !identifierPattern.MatchString(functionName) {
		return nil, fmt.Errorf("target function name %q is not a plain identifier", functionName)
	}
	encodedSeeds := make([]string, 0, len(seeds))
	for _, seed := range seeds {
		encodedSeeds = append(encodedSeeds, base64.StdEncoding.EncodeToString(seed))
	}
	seedLiteral := "nil"
	if len(encodedSeeds) > 0 {
		quoted := make([]string, 0, len(encodedSeeds))
		for _, seed := range encodedSeeds {
			quoted = append(quoted, strconv.Quote(seed))
		}
		seedLiteral = "[]string{" + strings.Join(quoted, ", ") + "}"
	}
	replacer := strings.NewReplacer(
		"@IMPORT_QUOTED@", strconv.Quote(importPath),
		"@IMPORT_TEXT@", importPath,
		"@FUNC_TEXT@", functionName,
		"@KIND_TEXT@", contractKind,
		"@SEED_DATA@", seedLiteral,
		"@TAG_FLOAT@", "`json:\"__float__\"`",
	)
	return []byte(replacer.Replace(targetTemplate)), nil
}

const targetTemplate = `// Code generated by PatchProof go-native-fuzz. DO NOT EDIT.

package patchprooffuzz

import (
	"bytes"
	"encoding/base64"
	"encoding/binary"
	"encoding/json"
	"fmt"
	"math"
	"reflect"
	"testing"

	targetpkg @IMPORT_QUOTED@
)

// Contract kind: @KIND_TEXT@. Any panic is a crash finding. For "safety"
// contracts this is also the contract's no-panic invariant; no fix-invariant
// expression is invented because the contract language cannot express one.
const maxArgumentBytes = 1 << 20

var seedData = @SEED_DATA@

func FuzzTarget(f *testing.F) {
	seeds := seedCorpus()
	if len(seeds) == 0 {
		f.Add([]byte{})
	}
	for _, seed := range seeds {
		f.Add(seed)
	}
	f.Fuzz(func(t *testing.T, data []byte) {
		args, ok := decodeArguments(data)
		if !ok {
			return
		}
		if panicValue := callTarget(args); panicValue != nil {
			t.Fatalf("target @IMPORT_TEXT@.@FUNC_TEXT@ panicked: %s", panicValue)
		}
	})
}

func seedCorpus() [][]byte {
	out := make([][]byte, 0, len(seedData))
	for _, encoded := range seedData {
		decoded, err := base64.StdEncoding.DecodeString(encoded)
		if err != nil {
			continue
		}
		out = append(out, decoded)
	}
	return out
}

func targetType() reflect.Type {
	typ := reflect.TypeOf(targetpkg.@FUNC_TEXT@)
	if typ == nil || typ.Kind() != reflect.Func || typ.IsVariadic() || typ.NumIn() > 32 {
		return nil
	}
	return typ
}

func decodeArguments(data []byte) ([]reflect.Value, bool) {
	if args, ok := decodePackedArguments(data); ok {
		return args, true
	}
	// A raw JSON array is accepted as a fallback so that byte-level fuzzing can
	// mutate textual arguments directly instead of only corrupting the length
	// prefix of the packed codec.
	return decodeJSONArguments(data)
}

func decodePackedArguments(data []byte) ([]reflect.Value, bool) {
	typ := targetType()
	if typ == nil {
		return nil, false
	}
	position := 0
	args := make([]reflect.Value, typ.NumIn())
	for index := 0; index < typ.NumIn(); index++ {
		if position+4 > len(data) {
			return nil, false
		}
		length := int(binary.BigEndian.Uint32(data[position:]))
		position += 4
		if length < 0 || length > maxArgumentBytes || position+length > len(data) {
			return nil, false
		}
		raw := data[position : position+length]
		position += length
		value := reflect.New(typ.In(index))
		if !decodeArgument(raw, value.Elem()) {
			return nil, false
		}
		args[index] = value.Elem()
	}
	if position != len(data) {
		return nil, false
	}
	return args, true
}

func decodeJSONArguments(data []byte) ([]reflect.Value, bool) {
	typ := targetType()
	if typ == nil {
		return nil, false
	}
	var rawArguments []json.RawMessage
	if err := json.Unmarshal(data, &rawArguments); err != nil {
		return nil, false
	}
	if len(rawArguments) != typ.NumIn() {
		return nil, false
	}
	args := make([]reflect.Value, len(rawArguments))
	for index, raw := range rawArguments {
		value := reflect.New(typ.In(index))
		if !decodeArgument(raw, value.Elem()) {
			return nil, false
		}
		args[index] = value.Elem()
	}
	return args, true
}

func decodeArgument(raw []byte, target reflect.Value) bool {
	if target.Kind() == reflect.Float32 || target.Kind() == reflect.Float64 {
		trimmed := bytes.TrimSpace(raw)
		if len(trimmed) > 0 && trimmed[0] == '{' {
			var special struct {
				Float *string @TAG_FLOAT@
			}
			if err := json.Unmarshal(trimmed, &special); err == nil && special.Float != nil {
				switch *special.Float {
				case "NaN":
					target.SetFloat(math.NaN())
					return true
				case "+Inf":
					target.SetFloat(math.Inf(1))
					return true
				case "-Inf":
					target.SetFloat(math.Inf(-1))
					return true
				}
			}
		}
	}
	return json.Unmarshal(raw, target.Addr().Interface()) == nil
}

func callTarget(args []reflect.Value) (recovered interface{}) {
	defer func() {
		if value := recover(); value != nil {
			recovered = describePanic(value)
		}
	}()
	reflect.ValueOf(targetpkg.@FUNC_TEXT@).Call(args)
	return nil
}

func describePanic(value interface{}) string {
	if err, ok := value.(error); ok {
		name := "error"
		if typ := reflect.TypeOf(err); typ != nil {
			name = typ.String()
		}
		return fmt.Sprintf("%s: %s", name, err.Error())
	}
	name := "interface{}"
	if typ := reflect.TypeOf(value); typ != nil {
		name = typ.String()
	}
	return fmt.Sprintf("%s: %v", name, value)
}
`
