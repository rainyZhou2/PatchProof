package gofuzz

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const packageDirName = ".patchproof"

// installTarget writes the generated fuzz target into the head snapshot. Only
// files owned by this engine are created and removed.
func installTarget(headDir string, source []byte) (func(), error) {
	root := filepath.Join(headDir, packageDirName)
	if _, err := os.Stat(root); err != nil && !os.IsNotExist(err) {
		return nil, fmt.Errorf("stat %s: %w", root, err)
	}
	if err := os.MkdirAll(root, 0o755); err != nil {
		return nil, fmt.Errorf("create fuzz package directory: %w", err)
	}
	testdataDir := filepath.Join(root, "testdata")
	_, testdataErr := os.Stat(testdataDir)
	testdataExisted := testdataErr == nil
	files := map[string][]byte{
		"doc.go":              []byte("// Code generated by PatchProof go-native-fuzz. DO NOT EDIT.\n\npackage patchprooffuzz\n"),
		"fuzz_target_test.go": source,
	}
	written := make([]string, 0, len(files))
	cleanup := func() {
		cleanupFiles(written, root, testdataExisted)
	}
	for name, content := range files {
		path := filepath.Join(root, name)
		if _, err := os.Stat(path); err == nil {
			cleanup()
			return nil, fmt.Errorf("refusing to overwrite existing %s", path)
		} else if !os.IsNotExist(err) {
			cleanup()
			return nil, fmt.Errorf("stat %s: %w", path, err)
		}
		if err := os.WriteFile(path, content, 0o644); err != nil {
			cleanup()
			return nil, fmt.Errorf("write fuzz target %s: %w", name, err)
		}
		written = append(written, path)
	}
	return cleanup, nil
}

// cleanupFiles removes only files created by this engine and drops the package
// directory when it is empty; unrelated files in .patchproof are preserved.
func cleanupFiles(written []string, root string, testdataExisted bool) {
	for _, path := range written {
		_ = os.Remove(path)
	}
	if !testdataExisted {
		_ = os.RemoveAll(filepath.Join(root, "testdata"))
	}
	_ = os.Remove(root)
}

// corpusFiles lists fuzz crash corpus entries written by the Go fuzzing engine.
func corpusFiles(headDir string) []string {
	dir := filepath.Join(headDir, packageDirName, "testdata", "fuzz", "FuzzTarget")
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	out := make([]string, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		out = append(out, filepath.Join(dir, entry.Name()))
	}
	sort.Strings(out)
	return out
}

// classifyFuzzOutput distinguishes crash findings from build/setup failures.
func classifyFuzzOutput(output string) (crash bool, buildFailure bool) {
	crash = strings.Contains(output, "--- FAIL: FuzzTarget") ||
		strings.Contains(output, "Failing input written to") ||
		strings.Contains(output, "testdata/fuzz/FuzzTarget")
	buildFailure = strings.Contains(output, "[build failed]") ||
		strings.Contains(output, "build failed") ||
		strings.Contains(output, "setup failed") ||
		strings.Contains(output, "no required module") ||
		strings.Contains(output, "cannot find package") ||
		strings.Contains(output, "undefined:") ||
		strings.Contains(output, "is not a function") ||
		strings.Contains(output, "flag provided but not defined") ||
		strings.Contains(output, "no Go files in")
	if crash {
		buildFailure = false
	}
	return crash, buildFailure
}

func truncateOutput(output string) string {
	const limit = 8 << 20
	if len(output) <= limit {
		return output
	}
	return output[:limit] + "\n...(truncated)"
}

func readBounded(path string, limit int64) ([]byte, error) {
	info, err := os.Stat(path)
	if err != nil {
		return nil, err
	}
	if info.Size() > limit {
		return nil, fmt.Errorf("file exceeds %d bytes", limit)
	}
	return os.ReadFile(path)
}
